        '<ol>'
        '<li>Generate the artwork externally, using the prompts below.</li>'
        '<li>Save the raw files, unmodified, into <code>07_ASSETS/raw/cover/</code> '
        'and <code>07_ASSETS/raw/aplus/</code> using the exact filenames given '
        'in each output contract.</li>'
        '<li>Run <code>python3 04_BUILD/cover_artwork.py</code>. It checksums '
        'every raw file, measures its real effective DPI against the target '
        'trim, and tells you whether it needs upscaling.</li>'
        '<li>Nothing overwrites a raw file, ever. Processing writes new files '
        'into <code>07_ASSETS/processed/</code> and <code>print/</code>.</li>'
        '</ol>',

        '<h3>On resolution, and the difference that matters</h3>',
        '<div class="box"><p>There are two different things people call '
        '"300 DPI" and only one of them is real.</p>'
        '<p><strong>Writing a 300 DPI tag into the file changes nothing.</strong> '
        'The pixel count is what prints. A 1024-pixel-wide image labelled '
        '300 DPI is still a 1024-pixel-wide image, and at 8.5 inches wide it '
        'prints at 120 effective DPI and looks like it.</p>'
        '<p><strong>Effective DPI is arithmetic:</strong> '
        '<code>pixels ÷ physical inches</code>. For this cover the front panel '
        'is %.3f in wide including bleed, so a raw file needs at least '
        '<strong>%d px</strong> across it to reach 300 effective DPI. That is '
        'the number to check, and <code>cover_artwork.py</code> checks it.</p>'
        '<p>The project\'s approved route to more pixels is real AI upscaling, '
