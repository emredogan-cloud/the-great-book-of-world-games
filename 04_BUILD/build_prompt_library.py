OUT_REL = os.path.join("07_ASSETS", "IMAGE_PROMPT_LIBRARY.html")


def load(p):
    with open(p, encoding="utf-8") as fh:
        return json.load(fh)


def E(s):
    return html.escape(str(s))


def ul(items, cls=""):
    return ('<ul class="%s">' % cls) + "".join(
        "<li>%s</li>" % E(i) for i in items) + "</ul>"


def kv(rows):
    return ("<table class=spec><tbody>" + "".join(
        "<tr><th>%s</th><td>%s</td></tr>" % (E(k), v if isinstance(v, str)
                                             and v.startswith("<") else E(v))
        for k, v in rows) + "</tbody></table>")


